"""Conventions for the private research lab (alpha-lab): findings format + index.

Every study folder `<lab>/<venue>/<study>/` carries a FINDINGS.md whose first block is
machine-readable `- key: value` lines, so the lab can be indexed and audited:

    # Title
    - status: draft | reviewed | superseded
    - evidence: description | proxy | simulation | live
    - date: YYYY-MM-DD
    - verdict: one hedged sentence that does not claim more than `evidence`
    - run: <run tag>            (optional but expected once a run exists)
    - toolkit: <quant-research git sha>   (optional)

`qr-index <lab root>` rebuilds INDEX.md and reports studies with missing/invalid fields.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

STATUSES = {"draft", "reviewed", "superseded"}
EVIDENCE = {"description", "proxy", "simulation", "live"}
REQUIRED = ("status", "evidence", "date", "verdict")

FINDINGS_TEMPLATE = """# {name}

- status: draft
- evidence: description
- date: {date}
- verdict: TODO one hedged sentence, no stronger than the evidence level
- run: TODO run tag
- toolkit: TODO quant-research git sha

## Result
What was measured, on what data (coverage, n, clock), in 3-6 lines.

## Numbers
| measure | value | n | note |
|---|---|---|---|

## Does NOT establish
- (e.g. not a fill rate, not executable edge, not durable; sample is N days / M markets)

## Reproduce
`uv run python {venue}/{slug}/study.py --src <data> --tag <tag>`

## Next
- smallest missing validation before a stronger claim
"""


def parse_findings(text: str) -> dict:
    out: dict = {}
    for line in text.splitlines():
        if line.startswith("# ") and "title" not in out:
            out["title"] = line[2:].strip()
        elif line.startswith("## "):
            break
        elif m := re.match(r"^- (\w+):\s*(.*)$", line):
            out[m[1]] = m[2].strip()
    return out


def check(meta: dict) -> list[str]:
    problems = [f"missing '{k}'" for k in REQUIRED if not meta.get(k) or meta[k].startswith("TODO")]
    if meta.get("status") and meta["status"] not in STATUSES:
        problems.append(f"status '{meta['status']}' not in {sorted(STATUSES)}")
    if meta.get("evidence") and meta["evidence"] not in EVIDENCE:
        problems.append(f"evidence '{meta['evidence']}' not in {sorted(EVIDENCE)}")
    if meta.get("date") and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", meta["date"]):
        problems.append("date must be YYYY-MM-DD")
    return problems


def scan(root) -> list[dict]:
    """One row per `<venue>/<study>/FINDINGS.md` (dirs starting with '_' or '.' are skipped)."""
    root = Path(root)
    rows = []
    for f in sorted(root.glob("*/*/FINDINGS.md")):
        venue, study = f.parts[-3], f.parts[-2]
        if venue.startswith(("_", ".")) or study.startswith(("_", ".")):
            continue
        meta = parse_findings(f.read_text())
        rows.append({"venue": venue, "study": study, **meta, "problems": check(meta)})
    return rows


def render_index(rows: list[dict]) -> str:
    head = ["# Findings index", "", "_Generated by `qr-index`; edit each study's FINDINGS.md, not this file._", "",
            "| venue | study | status | evidence | date | verdict |", "|---|---|---|---|---|---|"]
    body = [f"| {r['venue']} | [{r['study']}]({r['venue']}/{r['study']}/FINDINGS.md) | {r.get('status', '-')} | "
            f"{r.get('evidence', '-')} | {r.get('date', '-')} | {(r.get('verdict') or '-').replace('|', '/')} |" for r in rows]
    return "\n".join(head + body) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", nargs="?", default=None, help="lab root (default: $ALPHA_LAB or ~/Documents/Github/alpha-lab)")
    ap.add_argument("--check", action="store_true", help="exit 1 if any study has missing/invalid fields")
    a = ap.parse_args(argv)
    from quant_research.scaffold import lab_root
    root = Path(a.root).expanduser() if a.root else lab_root()
    rows = scan(root)
    (root / "INDEX.md").write_text(render_index(rows))
    bad = [r for r in rows if r["problems"]]
    for r in bad:
        print(f"{r['venue']}/{r['study']}: " + "; ".join(r["problems"]))
    print(f"{len(rows)} studies indexed -> {root / 'INDEX.md'}; {len(bad)} with problems")
    if a.check and bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
